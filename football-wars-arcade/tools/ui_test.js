// Browser UI flow tests (Playwright + the pre-installed Chromium). Real clicks on the built single HTML file.
const { chromium } = require('playwright'); const path = require('path'); const fs = require('fs');
const OUT = process.env.SHOTS || '.'; const FILE = 'file://' + path.resolve(__dirname, '../FootballWars_Arcade.html');
let pass = 0, fail = 0; const T = (n, ok, info) => { ok ? pass++ : fail++; console.log((ok ? 'PASS ' : 'FAIL ') + n + (info !== undefined ? '  ' + JSON.stringify(info) : '')); };
(async () => {
  const b = await chromium.launch();
  const ctx = await b.newContext({ viewport: { width: 400, height: 820 }, hasTouch: true, isMobile: true, acceptDownloads: true });
  const p = await ctx.newPage(); const errs = [];
  p.on('pageerror', e => errs.push(e.message)); p.on('console', m => { if (m.type() === 'error') errs.push(m.text()); });
  await ctx.route('**/*', r => r.request().url().startsWith('file:') ? r.continue() : (errs.push('NET ' + r.request().url()), r.abort()));
  const S = () => p.evaluate(() => JSON.parse(JSON.stringify(ArcadeApp.st.save)));
  const shot = n => p.screenshot({ path: OUT + '/' + n + '.png' });
  const finishBattle = async () => { for (let i = 0; i < 200; i++) { await p.waitForTimeout(400); if (await p.evaluate(() => !ArcadeApp.st.battle)) return; if (await p.evaluate(() => ArcadeApp.st.battle.ended)) await p.click('#btSkip').catch(() => {}); } };
  await p.goto(FILE); await p.waitForTimeout(400);
  await p.fill('#clubSearch', 'fenerbah'); await p.waitForTimeout(100);
  T('UI1 search by source name finds adapted club', (await p.$$eval('.clubrow b', r => r.map(x => x.textContent))).includes('Fener İstanbul'));
  await p.click('.clubrow'); await p.click('#startBtn'); await p.waitForTimeout(300);
  await p.evaluate(() => { ArcadeApp.st.save.credits = 5000; ArcadeApp.persist(); ArcadeApp.render(); }); // test shortcut: credits to exercise spending UI
  await p.click('#tabbar [data-tab="upgrades"]'); await p.waitForTimeout(150);
  await p.click('[data-act="up:attack"]'); await p.waitForTimeout(100);
  let s = await S(); T('UI2 upgrade button spends 90 C, Lv2', s.credits === 4910 && s.upgrades.attack === 2);
  await shot('10_upgrades');
  await p.click('#tabbar [data-tab="packs"]'); await p.waitForTimeout(150);
  await p.click('[data-act="open:standard:credits"]'); await p.waitForTimeout(500);
  T('UI3 pack opening animation shown', !!(await p.$('.opening')));
  await p.click('.opening'); await p.waitForTimeout(700);
  const cands = await p.$$eval('#draftBox [data-pick] .nm', r => r.map(x => x.textContent));
  T('UI4 three candidates visible', cands.length === 3, cands);
  await shot('11_draft');
  await p.reload(); await p.waitForTimeout(600);
  s = await S(); T('UI5 after reload: draft still pending, paid once', !!s.pendingDraft && s.credits === 4910 - 450 && s.packCounter === 1);
  const before = s.pendingDraft.cands.map(c => c.id);
  await p.click('[data-act="draft"]').catch(() => {}); await p.waitForTimeout(300);
  const cands2 = await p.$$eval('#draftBox [data-pick]', r => r.map(x => x.dataset.star));
  T('UI6 reloaded draft shows identical stars', JSON.stringify(cands2) === JSON.stringify(before), cands2);
  await p.click('#draftBox [data-pick="2"]'); await p.click('#draftBox [data-sign]'); await p.waitForTimeout(300);
  s = await S(); T('UI7 signed exactly one star (auto-equipped)', Object.keys(s.stars).length === 1 && !!s.stars[before[2]] && s.active.length === 1 && !s.pendingDraft);
  await p.click('#tabbar [data-tab="stars"]'); await p.waitForTimeout(200); await shot('12_collection');
  await p.click('#screen .stars [data-star]'); await p.waitForTimeout(200);
  T('UI8 star detail modal with actions', !!(await p.$('#modal [data-m="remove"]')));
  await p.click('#modal [data-m="remove"]'); s = await S(); T('UI9 remove from active (free)', s.active.length === 0);
  await p.click('#screen .stars [data-star]'); await p.click('#modal [data-m="equip"]'); s = await S(); T('UI10 equip again', s.active.length === 1);
  const cBefore = s.stars[before[2]].contract;
  await p.click('#tabbar [data-tab="home"]'); await p.click('.battle-btn'); await p.waitForTimeout(5200);
  s = await S(); T('UI11 battle start used 1 contract match', s.stars[before[2]].contract === cBefore - 1 && !!s.pendingBattle, [cBefore, s.stars[before[2]].contract]);
  const savedTick = (await S()).pendingBattle.lastTick;
  await p.reload(); await p.waitForTimeout(600); // simulates closing the browser mid-battle
  T('UI12 resume dialog after reload', !!(await p.$('#modal [data-m="resume"]')), { savedTick });
  await shot('13_resume');
  await p.click('#modal [data-m="resume"]'); await p.waitForTimeout(1500);
  const rt = await p.evaluate(() => ArcadeApp.st.battle && ArcadeApp.st.battle.w.tick);
  s = await S(); T('UI13 resumed from saved tick, contract not reduced again', savedTick > 0 && rt >= savedTick && s.stars[before[2]].contract === cBefore - 1, { savedTick, rt });
  await p.click('#btSpeed');
  await finishBattle(); await p.waitForTimeout(300); await shot('14_results');
  s = await S(); T('UI14 battle finished, result recorded', !s.pendingBattle && (s.league.round === 1 || !!s.pendingDecision));
  if (s.pendingDecision) await p.click('#modal [data-m="accept"]'); else await p.click('#modal [data-m="next"]');
  await p.waitForTimeout(200);
  s = await S(); T('UI15 fixture 1 finalised once (rewards in)', s.league.round === 1 && s.officialPlayed === 1 && s.xp > 0);
  for (let k = 0; k < 2; k++) {
    await p.click('[data-act="quick"]'); await p.waitForTimeout(200);
    for (let i = 0; i < 80; i++) { await p.waitForTimeout(250); if (await p.$('#modal [data-m="next"], #modal [data-m="accept"]')) break; }
    if (await p.$('#modal [data-m="accept"]')) await p.click('#modal [data-m="accept"]'); else await p.click('#modal [data-m="next"]');
    await p.waitForTimeout(150);
  }
  s = await S(); T('UI16 quick simulate works (3 fixtures done, free pack)', s.officialPlayed === 3 && s.packs.standard === 1, { played: s.officialPlayed, packs: s.packs });
  for (let i = 0; i < 120 && (await S()).league.aiQueue.length; i++) await p.waitForTimeout(250);
  s = await S(); T('UI17 background AI simulated the rounds (27 AI results)', Object.values(s.league.results).filter(r => r.ai).length === 27, s.league.aiQueue.length);
  await p.click('#tabbar [data-tab="league"]'); await p.waitForTimeout(200); await shot('15_league');
  await p.click('#tabbar [data-tab="challenges"]'); await p.waitForTimeout(200); await shot('16_challenges');
  T('UI18 challenge board unlocked with 3 cards', (await p.$$('[data-act^="ch:10:"]')).length === 3);
  await p.click('[data-act="ch:10:last"]'); await p.waitForTimeout(500);
  T('UI19 challenge battle runs live (no quick sim)', await p.evaluate(() => !!ArcadeApp.st.battle && !!ArcadeApp.st.battle.w));
  await p.click('#btPause'); await p.waitForTimeout(150); await shot('17_pause');
  await p.click('#pauseBox [data-b="abandon"]'); await p.waitForTimeout(300);
  s = await S(); T('UI20 abandon = recorded loss, no reward', !s.pendingBattle && s.challenges.done['D10:last'].plays === 1 && !s.challenges.done['D10:last'].won);
  await p.click('#modal [data-m="next"]').catch(() => {});
  await p.click('#topbar [data-act="settings"]'); await p.waitForTimeout(150); await shot('18_settings');
  const [dl] = await Promise.all([p.waitForEvent('download'), p.click('#modal [data-m="export"]')]);
  const fpath = OUT + '/export.json'; await dl.saveAs(fpath);
  const exp = JSON.parse(fs.readFileSync(fpath, 'utf8')); T('UI21 export JSON is a valid save', exp.kind === 'football-wars-arcade' && exp.club === 'TUR_FENERBAHCE');
  await p.evaluate(() => { ArcadeApp.st.save.credits = 1; ArcadeApp.persist(); });
  const [fc] = await Promise.all([p.waitForEvent('filechooser'), p.click('#modal [data-m="import"]')]);
  await fc.setFiles(fpath); await p.waitForTimeout(400);
  s = await S(); T('UI22 import restores the exported career', s.credits === exp.credits && s.officialPlayed === exp.officialPlayed);
  await p.evaluate(() => { ArcadeApp.st.save.settings.quality = 'low'; ArcadeApp.st.save.settings.mute = true; ArcadeApp.persist(); });
  await p.click('#tabbar [data-tab="home"]').catch(() => {}); await p.click('.battle-btn'); await p.waitForTimeout(800);
  T('UI23 Low quality + muted: still 100 v 100 and running', await p.evaluate(() => [0, 1].map(sd => ArcadeApp.st.battle.w.units.filter(u => u.side === sd).length).join() === '100,100'));
  await p.tap('#strikeBtn').catch(() => {});
  await p.click('#btPause'); await p.click('#pauseBox [data-b="abandon"]'); await p.waitForTimeout(200);
  T('UI24 no page errors / no network requests', errs.length === 0, errs.slice(0, 5));
  console.log('ui tests: ' + pass + ' pass, ' + fail + ' fail');
  await b.close();
})();
