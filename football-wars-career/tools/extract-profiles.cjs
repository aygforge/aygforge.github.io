// Extracts ANONYMISED battle-balance profiles from the V4 database. Real club names, ids, aliases, colours,
// countries and source ratings are dropped; only game-design profile values (power index, archetype,
// inferred attribute shape, specials, aggression) are kept and used as balance reference.
const fs = require('fs'), path = require('path');
globalThis.window = globalThis; eval(fs.readFileSync(process.argv[2], 'utf8'));
const db = globalThis.FW_MASTER_DB, cfg = globalThis.FW_ENGINE_CONFIG;
const prof = db.clubs.map(c => { const b = c.battle_profile; return { p: b.power_index, a: b.archetype, at: b.attributes, sp: b.specials, ag: b.aggression }; });
prof.sort((x, y) => y.p - x.p || y.ag - x.ag);
const variance = db.clubs[0].battle_profile.variance;
const src = `// AUTO-GENERATED by tools/extract-profiles.cjs — anonymised balance profiles derived from the V4 database
// (194 entries). No club names, ids, crests or colours. Power indices are derived from beyondELO club
// ratings (CC BY 4.0, https://beyondelo.com); attributes/archetypes are game-design interpretations.
export const PROFILES = ${JSON.stringify(prof)};
export const VARIANCE = ${JSON.stringify(variance)};
export const ENGINE_CFG = ${JSON.stringify({ simulation_engine_recommendation: cfg.simulation_engine_recommendation, archetype_definitions: cfg.archetype_definitions })};
`;
fs.writeFileSync(path.resolve(__dirname, '../src/data/profiles.js'), src);
console.log('profiles', prof.length, 'variance', JSON.stringify(variance));
